export default function AnimatedLogo({ className = "" }) {
  const [animate] = useState(() => {
    try {
      if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return false;
      return !sessionStorage.getItem(SEEN_KEY);
    } catch {
      return false;
    }
  });

  useEffect(() => {
    if (!animate) return;
    try {
      sessionStorage.setItem(SEEN_KEY, "1");
    } catch {
      // تجاهل أخطاء التخزين (مثلاً في وضع التصفح الخاص)
    }
  }, [animate]);

  return (
    <>
      {animate && <style>{CSS}</style>}
      <svg
        viewBox="0 0 1060 296"
        width="1060"
        height="296"
        role="img"
        aria-label="Trend Shop"
        className={className}
      >
        {PATHS.map((p, i) =>
          animate ? (
            <path
              key={i}
              pathLength="1"
              fillRule="evenodd"
              d={p.d}
              className="tl-p"
              style={{ "--c": p.c, "--dl": `${p.dl}s`, "--t": `${p.t}s` }}
            />
          ) : (
            <path key={i} fillRule="evenodd" d={p.d} fill={p.c} />
          ),
        )}
      </svg>
    </>
  );
}